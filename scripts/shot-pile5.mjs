import { chromium } from 'playwright';
const out = process.argv[2], file = process.argv[3];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
await page.goto('file://' + file);
await page.waitForTimeout(400);
await page.getByText('Cabezal con pilotes preexcavados en roca (socket)').click();
await page.waitForTimeout(600);
await page.getByRole('tab', { name: /Suelo y efectos/ }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: out + '/rock1.png' });
await page.getByRole('tab', { name: /Resultados/ }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: out + '/rock2.png' });
await browser.close();
