import { chromium } from 'playwright';
const out = process.argv[2], file = process.argv[3];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const page = await browser.newPage({ viewport: { width: 1500, height: 950 } });
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
await page.goto('file://' + file);
await page.waitForTimeout(400);
await page.getByText('Mampostería reforzada en voladizo').first().click();
await page.waitForTimeout(600);
await page.getByText('Materiales y armado').click();
await page.waitForTimeout(300);
await page.getByText('Malla de la zapata corrida').scrollIntoViewIfNeeded();
await page.waitForTimeout(300);
await page.screenshot({ path: out + '/al1.png' });
await page.getByRole('tab', { name: /Armado/ }).click();
await page.locator('.right').evaluate((e) => e.scrollTo(0, 400));
await page.waitForTimeout(300);
await page.screenshot({ path: out + '/al2.png' });
await browser.close();
