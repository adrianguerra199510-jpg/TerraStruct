import { chromium } from 'playwright';
import { readFileSync, writeFileSync } from 'fs';
const out = process.argv[2];
const file = process.argv[3];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const page = await browser.newPage({ viewport: { width: 1500, height: 950 } });
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
await page.goto('file://' + file);
await page.waitForTimeout(500);
await page.getByTitle('Importar zapatas desde Excel (por paquete)').click();
const dl = page.waitForEvent('download');
await page.getByText('Descargar plantilla').click();
const d = await dl; await d.saveAs(out + '/plantilla.xlsx');
await page.locator('input[accept*=xlsx]').setInputFiles(out + '/plantilla.xlsx');
await page.waitForTimeout(500);
await page.getByRole('button', { name: /Dimensionar 3/ }).click();
await page.waitForTimeout(4000);
await page.screenshot({ path: out + '/import.png' });
await page.getByRole('button', { name: /Crear 3/ }).click();
await page.waitForTimeout(800);
await page.getByRole('tab', { name: /Resultados/ }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: out + '/after.png' });
await browser.close();
