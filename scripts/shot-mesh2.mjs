import { chromium } from 'playwright';
const out = process.argv[2];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const page = await b.newPage({ viewport: { width: 1500, height: 950 }, acceptDownloads: true });
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
await page.goto('http://localhost:4173/');
await page.getByText('Diseñar un muro').click();
await page.locator('.type-card', { hasText: 'Contrafuerte int.' }).click();
await page.locator('summary', { hasText: 'Materiales y armado' }).click();
await page.locator('summary', { hasText: 'Suelos, agua y empuje' }).click();
await page.locator('summary', { hasText: 'Tipología del muro' }).click();
await page.locator('summary', { hasText: 'Geometría' }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/cf2-panel.png` });
await page.getByRole('tab', { name: /Diseño/ }).click(); await page.waitForTimeout(400);
await page.locator('.split > .right').evaluate((e) => e.scrollTo(0, 420));
await page.screenshot({ path: `${out}/cf2-diseno.png` });
await page.getByRole('tab', { name: /Armado/ }).click(); await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/cf2-armado.png` });
await b.close();
