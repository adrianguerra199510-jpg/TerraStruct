// Captura de pantalla de la aplicación (para revisión visual durante el desarrollo).
import { chromium } from 'playwright';
const out = process.argv[2];
const base = process.argv[3] || 'http://localhost:4173/';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome' });
const page = await browser.newPage({ viewport: { width: 1500, height: 950 } });
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
await page.goto(base);
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/home.png` });
await page.getByText('Diseñar una fundación').click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/footing-planta.png` });
await page.getByRole('tab', { name: /Resultados/ }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/footing-resultados.png`, fullPage: false });
await page.getByRole('tab', { name: /Armado/ }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/footing-armado.png` });
await page.getByText('Muros de retención').first().click();
await page.waitForTimeout(300);
await page.locator('.nav-btn', { hasText: 'Muro M-1' }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/wall-seccion.png` });
await page.getByRole('tab', { name: /Estabilidad/ }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/wall-estab.png` });
await page.getByRole('tab', { name: /Diseño/ }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/wall-diseno.png` });
await page.getByRole('tab', { name: /Armado/ }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/wall-armado.png` });
await browser.close();
